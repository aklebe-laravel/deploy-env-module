<?php

namespace Modules\DeployEnv\tests\Feature;

use Modules\DeployEnv\app\Services\DeploymentService;
use Modules\SystemBase\tests\TestCase;

class EnvVarTest extends TestCase
{
    /**
     * @return void
     */
    public function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub
    }

    /**
     * @return void
     */
    public function tearDown(): void
    {
        parent::tearDown(); // TODO: Change the autogenerated stub
    }

    /**
     * Testing git pulls to storage/tests/git_pulls/xxx
     *
     * Testing results of
     * GitService::findSatisfiedVersion()
     * GitService::findSatisfiedBranch()
     */
    public function test_parse_env(): void
    {
        $envContent = <<<EOT
APP_NAME="ProxTop"
APP_VERSION="2.0.0"
APP_ENV=local
APP_LOCALE=de
REDIS_PREFIX="proxtop_redis_"
CACHE_PREFIX="proxtop_cache_"
APP_KEY=base64:aIJkKw6xHZkYxjmeV6DipSlLne6siX4iNEffZk63Zu0=
APP_DEBUG=true
DEBUGBAR_ENABLED=true
APP_DOMAIN="prox-top.dev.example.com"
APP_URL="https://\${APP_DOMAIN}/\${{unknown_var_x var1='4'   var_y='abc' var_z="\${{another_var_xyz}}" }}"
FORCE_HTTPS=true
CONFIG_CACHE=false

LOG_CHANNEL=stack
LOG_MAX_FILES=7
LOG_DEPRECATIONS_CHANNEL=null
LOG_LEVEL=debug
LOG_STACK=daily,stderr
EOT;

        $result = app(DeploymentService::class)->parseEverything($envContent);
        $env1 = env('APP_DOMAIN');

        $envContentExpected = <<<EOT
APP_NAME="ProxTop"
APP_VERSION="2.0.0"
APP_ENV=local
APP_LOCALE=de
REDIS_PREFIX="proxtop_redis_"
CACHE_PREFIX="proxtop_cache_"
APP_KEY=base64:aIJkKw6xHZkYxjmeV6DipSlLne6siX4iNEffZk63Zu0=
APP_DEBUG=true
DEBUGBAR_ENABLED=true
APP_DOMAIN="prox-top.dev.example.com"
APP_URL="https://$env1/\${{unknown_var_x var1='4'   var_y='abc' var_z="\${{another_var_xyz}}" }}"
FORCE_HTTPS=true
CONFIG_CACHE=false

LOG_CHANNEL=stack
LOG_MAX_FILES=7
LOG_DEPRECATIONS_CHANNEL=null
LOG_LEVEL=debug
LOG_STACK=daily,stderr
EOT;

        $this->assertTrue($result == $envContentExpected);
    }
}
